// SendMailRequest is one outbound message.
type SendMailRequest struct {
	From    string   // the mailbox to send AS; needs Mail.Send on the app
	To      []string // recipients
	CC      []string // copied recipients; subject to the caller's allowlist too
	Subject string
	HTML    string // body, contentType HTML
	// HighImportance flags the message. Reserved for genuine Sev5 alerts: a
	// system that marks everything urgent has marked nothing urgent.
	HighImportance bool

	// Attachments are inlined into the sendMail payload as base64, which is
	// what Graph accepts for anything under its size limit. The caller decides
	// what is small enough; this package does not silently drop one.
	Attachments []Attachment

	// SaveToSentItems is a pointer so that nil means true - the behaviour
	// every existing caller already relies on. A plain bool would make the
	// zero value "do not save", silently changing what cti-alert does the
	// moment this field was added.
	SaveToSentItems *bool
}

// Attachment is one file inlined into a message.
type Attachment struct {
	Name        string
	ContentType string
	Bytes       []byte
}

type sendMailPayload struct {
	Message struct {
		Subject string `json:"subject"`
		Body    struct {
			ContentType string `json:"contentType"`
			Content     string `json:"content"`
		} `json:"body"`
		ToRecipients []recipient      `json:"toRecipients"`
		CCRecipients []recipient      `json:"ccRecipients,omitempty"`
		Importance   string           `json:"importance"`
		Attachments  []fileAttachment `json:"attachments,omitempty"`

		// Headers we set on our own outgoing mail. Graph requires custom
		// header names to begin with "X-".
		Headers []messageHeader `json:"internetMessageHeaders,omitempty"`
	} `json:"message"`
	SaveToSentItems bool `json:"saveToSentItems"`
}

type messageHeader struct {
	Name  string `json:"name"`
	Value string `json:"value"`
}

// fileAttachment is Graph's inline attachment shape. The @odata.type is
// required and the API rejects the message without it.
type fileAttachment struct {
	ODataType    string `json:"@odata.type"`
	Name         string `json:"name"`
	ContentType  string `json:"contentType"`
	ContentBytes string `json:"contentBytes"`
}

type recipient struct {
	EmailAddress struct {
		Address string `json:"address"`
	} `json:"emailAddress"`
}

// SendMail sends one message as the given mailbox via Graph sendMail.
//
// This reuses the same app registration and token path the mailbox reader
// uses, so the only extra requirement is the Mail.Send application permission
// with admin consent.
//
// It returns the Graph request-id on success. sendMail answers 202 with an
// empty body, so there is no message id to report - request-id is what
// Microsoft support asks for when a message goes missing.
// SendMailResult is what the send actually returned.
//
// The status code is here because the caller logs it and mailer.py logged the
// real one. Hardcoding 202 - the code Graph returns today - would be a report
// of what we expected rather than what happened, which is the distinction this
// codebase keeps having to relearn.
type SendMailResult struct {
	RequestID string
	Status    int
}

func (c *Client) SendMail(ctx context.Context, req SendMailRequest) (SendMailResult, error) {
	if req.From == "" {
		return SendMailResult{}, fmt.Errorf("SendMail: From is required (the sending mailbox)")
	}
	if len(req.To) == 0 {
		// No default recipient, deliberately. A hardcoded address is a
		// mis-send waiting to happen on someone else's tenant.
		return SendMailResult{}, fmt.Errorf("SendMail: at least one recipient is required")
	}
	if req.Subject == "" {
		return SendMailResult{}, fmt.Errorf("SendMail: Subject is required")
	}

	tok, err := c.token(ctx)
	if err != nil {
		return SendMailResult{}, err
	}

	var p sendMailPayload
	p.Message.Subject = req.Subject
	p.Message.Body.ContentType = "HTML"
	p.Message.Body.Content = req.HTML
	p.Message.Importance = "normal"
	if req.HighImportance {
		p.Message.Importance = "high"
	}
	for _, addr := range req.To {
		var r recipient
		r.EmailAddress.Address = addr
		p.Message.ToRecipients = append(p.Message.ToRecipients, r)
	}
	for _, addr := range req.CC {
		var r recipient
		r.EmailAddress.Address = addr
		p.Message.CCRecipients = append(p.Message.CCRecipients, r)
	}
	for _, a := range req.Attachments {
		ct := a.ContentType
		if ct == "" {
			ct = "application/octet-stream"
		}
		p.Message.Attachments = append(p.Message.Attachments, fileAttachment{
			ODataType:    "#microsoft.graph.fileAttachment",
			Name:         a.Name,
			ContentType:  ct,
			ContentBytes: base64.StdEncoding.EncodeToString(a.Bytes),
		})
	}
	// Stamp our own mail so the ingest can recognise it later.
	//
	// THE LOOP THIS CLOSES
	//
	// The digest is sent TO the same mailbox the digest READS. So yesterday's
	// digest arrives as today's input, the extractor pulls the CVEs out of our
	// own report, and they are presented as newly mentioned - every day,
	// forever. Observed 2026-10-04: "EMAILS READ THIS RUN - 2 total, 1
	// mentioning a CVE", and the one mentioning a CVE was the previous day's
	// own digest.
	//
	// It is self-sustaining. A CVE reported once stays in the mailbox as our
	// own mail and re-enters every subsequent run, so the daily can never go
	// quiet and the counts are fiction. Worse, nothing about it looks wrong:
	// the email is well-formed, the CVE is real, and the pipeline is working
	// exactly as written.
	//
	// A header rather than a sender check, because a header is something we
	// control and can assert in a test. The sender check in RecentMessages is
	// the backstop for mail already sitting in the mailbox from before this
	// existed.
	p.Message.Headers = append(p.Message.Headers, messageHeader{
		Name: SelfHeader, Value: req.From,
	})

	p.SaveToSentItems = true
	if req.SaveToSentItems != nil {
		p.SaveToSentItems = *req.SaveToSentItems
	}

	body, err := json.Marshal(p)
	if err != nil {
		return SendMailResult{}, err
	}

	endpoint := fmt.Sprintf("%s/users/%s/sendMail",
		c.graphBase, url.PathEscape(req.From))
	httpReq, err := http.NewRequestWithContext(ctx, http.MethodPost, endpoint,
		strings.NewReader(string(body)))
	if err != nil {
		return SendMailResult{}, err
	}
	httpReq.Header.Set("Authorization", "Bearer "+tok)
	httpReq.Header.Set("Content-Type", "application/json")

	resp, err := c.http.Do(httpReq)
	if err != nil {
		return SendMailResult{}, err
	}
	defer func() { _ = resp.Body.Close() }()
	respBody, err := io.ReadAll(resp.Body)
	if err != nil {
		return SendMailResult{}, fmt.Errorf("failed to read sendMail response: %w", err)
	}
	if resp.StatusCode < 200 || resp.StatusCode > 299 {
		return SendMailResult{}, sendMailError(resp.StatusCode, respBody, req.From)
	}

	reqID := resp.Header.Get("request-id")
	if reqID == "" {
		reqID = resp.Header.Get("client-request-id")
	}
	return SendMailResult{RequestID: reqID, Status: resp.StatusCode}, nil
}

// sendMailError annotates the failures that actually happen in practice,
// because "403 Forbidden" on its own sends people to the wrong place.
func sendMailError(status int, body []byte, mailbox string) error {
	trimmed := strings.TrimSpace(string(body))
	if len(trimmed) > 600 {
		trimmed = trimmed[:600] + "..."
	}
	switch {
	case status == 403 && strings.Contains(trimmed, "MailboxNotEnabledForRESTAPI"):
		return fmt.Errorf("sendMail 403: %s is not a REST-enabled mailbox "+
			"(shared mailboxes need a license, or it is on-prem): %s", mailbox, trimmed)
	case status == 403:
		return fmt.Errorf("sendMail 403: the app registration is probably missing "+
			"Mail.Send as an APPLICATION permission, or admin consent was never "+
			"granted, or an Application Access Policy excludes %s: %s", mailbox, trimmed)
	case status == 404:
		return fmt.Errorf("sendMail 404: mailbox %s not found - check the address "+
			"and that it is a real mailbox, not a distribution group: %s", mailbox, trimmed)
	default:
		return fmt.Errorf("sendMail failed: HTTP %d: %s", status, trimmed)
	}
}

// Folder is a destination this client is willing to move a message to.
//
// A closed set, not a string parameter, and it contains no way to express a
// permanent deletion. Moving to DeletedItems is the equivalent of pressing
// Delete in Outlook: the message sits in Deleted Items, then in Recoverable
// Items, and can be brought back. Graph's DELETE /messages/{id} and the
// purge endpoints are deliberately not implemented here - an automated lane
// that runs unattended every day should not have the vocabulary to destroy
// mail, and "we can add it later if needed" is how it ends up available at
// 3am to something that misidentified a message.
type Folder string

const (
	FolderArchive      Folder = "archive"
	FolderDeletedItems Folder = "deleteditems"
)

// MoveMessage moves one message to a well-known folder and returns the new
// message ID.
//
// Graph's move is a copy-then-delete, so the ID changes. The new ID is
// returned because the caller records what it did, and a record pointing at an
// ID that no longer resolves cannot be checked afterwards.
func (c *Client) MoveMessage(ctx context.Context, mailbox, messageID string, dest Folder) (string, error) {
	switch dest {
	case FolderArchive, FolderDeletedItems:
	default:
		return "", fmt.Errorf("MoveMessage: refusing unknown destination %q", dest)
	}
	if strings.TrimSpace(mailbox) == "" || strings.TrimSpace(messageID) == "" {
		return "", fmt.Errorf("MoveMessage: mailbox and messageID are both required")
	}

	tok, err := c.token(ctx)
	if err != nil {
		return "", err
	}
	endpoint := fmt.Sprintf("%s/users/%s/messages/%s/move",
		c.graphBase, url.PathEscape(mailbox), url.PathEscape(messageID))
	payload, err := json.Marshal(map[string]string{"destinationId": string(dest)})
	if err != nil {
		return "", err
	}
	req, err := http.NewRequestWithContext(ctx, http.MethodPost, endpoint, bytes.NewReader(payload))
	if err != nil {
		return "", err
	}
	req.Header.Set("Authorization", "Bearer "+tok)
	req.Header.Set("Content-Type", "application/json")

	resp, err := c.http.Do(req)
	if err != nil {
		return "", err
	}
	defer func() { _ = resp.Body.Close() }()
	body, err := io.ReadAll(io.LimitReader(resp.Body, 1<<20))
	if err != nil {
		return "", fmt.Errorf("MoveMessage: reading response: %w", err)
	}
	if resp.StatusCode < 200 || resp.StatusCode > 299 {
		return "", moveError(resp.StatusCode, body, mailbox, dest)
	}
	var moved struct {
		ID string `json:"id"`
	}
	// A 2xx with an unparseable body still means the move happened, so this is
	// not an error - the caller just cannot record the new ID.
	_ = json.Unmarshal(body, &moved)
	return moved.ID, nil
}

// moveError names the failure that will actually happen: the new permission
// not being granted.
func moveError(status int, body []byte, mailbox string, dest Folder) error {
	trimmed := strings.TrimSpace(string(body))
	if len(trimmed) > 600 {
		trimmed = trimmed[:600] + "..."
	}
	// Tagged switch: every case here is a plain status comparison, unlike
	// sendMailError above, which pairs a status with a body check and so has
	// to stay untagged.
	switch status {
	case http.StatusForbidden:
		return fmt.Errorf("move to %s 403: the app registration needs Mail.ReadWrite "+
			"as an APPLICATION permission with admin consent granted - Mail.Read is "+
			"not enough to move a message - or an Application Access Policy excludes "+
			"%s: %s", dest, mailbox, trimmed)
	case http.StatusNotFound:
		return fmt.Errorf("move to %s 404: message not found in %s. It may already "+
			"have been moved, by this lane or by a person: %s", dest, mailbox, trimmed)
	default:
		return fmt.Errorf("move to %s failed: HTTP %d: %s", dest, status, trimmed)
	}
}
