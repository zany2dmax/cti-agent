type Client struct {
	tenantID     string
	clientID     string
	clientSecret string
	http         *http.Client

	// Endpoints are fields rather than constants so tests can point them at a
	// local server. Without this the whole client was untestable without
	// network access, which is how an unescaped space in $orderby shipped.
	tokenEndpoint string // full URL; defaults to the Entra v2 token endpoint
	graphBase     string // scheme+host, no trailing slash
}

// sameAddress compares two mail addresses for identity.
//
// Case-insensitive on the whole address: the local part is technically
// case-sensitive per RFC 5321, but no mail system anybody runs treats it that
// way, and the cost of being pedantic here is failing to recognise our own
// digest because Exchange capitalised it differently in one place.
func sameAddress(a, b string) bool {
	a, b = strings.TrimSpace(a), strings.TrimSpace(b)
	return a != "" && strings.EqualFold(a, b)
}

// SelfHeader marks mail this fleet sent. Graph requires custom header names
// to start with "X-".
//
// Its value is the sending mailbox, so a shared tenant running two fleets can
// tell whose report it is looking at rather than discarding both.
const SelfHeader = "X-CTI-Agent-Sent"

// Graph returns header names in whatever case the sender used, so the match
// is done lowercased. Precomputed rather than lowercased inside the loop.
var selfHeaderLower = strings.ToLower(SelfHeader)

type Message struct {
	ID               string    `json:"id"`
	Subject          string    `json:"subject"`
	ReceivedDateTime time.Time `json:"receivedDateTime"`
	From             string
	BodyText         string

	// SelfSent is true when this message carries SelfHeader - that is, when
	// the fleet sent it. See the comment in SendMail for the loop this closes.
	SelfSent bool

	// AutoSubmitted and AutoResponseSuppress carry the RFC 3834 and Microsoft
	// headers that mark a message as machine-generated.
	//
	// Headers, not subject text. These decide whether a message is eligible to
	// be moved to Deleted Items, so precision matters more than recall: an
	// auto-reply that omits the headers stays in the inbox, which is a tidiness
	// problem, whereas a real advisory matched by a subject pattern would be
	// deleted, which is not.
	AutoSubmitted        string
	AutoResponseSuppress string
}

// IsAutoReply reports whether the sending system declared this an automatic
// reply.
//
// RFC 3834 reserves "auto-replied" for vacation notices and the like, and
// explicitly distinguishes it from "auto-generated" (a report or notification),
// which we do NOT treat as an auto-reply - a vendor advisory generated by a
// mailing system is auto-generated and must never be deleted.
func (m Message) IsAutoReply() bool {
	switch strings.ToLower(strings.TrimSpace(m.AutoSubmitted)) {
	case "auto-replied", "auto-notified":
		return true
	}
	// Exchange sets this on out-of-office replies. "All" is what an OOF
	// template sends; the presence of the header alone is not enough, since
	// other automated mail sets it to suppress further responses.
	if strings.EqualFold(strings.TrimSpace(m.AutoResponseSuppress), "All") &&
		strings.Contains(strings.ToLower(m.AutoSubmitted), "auto") {
		return true
	}
	return false
}

type tokenResponse struct {
	AccessToken string `json:"access_token"`
	TokenType   string `json:"token_type"`
	ExpiresIn   int    `json:"expires_in"`
}

type messagesResponse struct {
	Value []struct {
		ID               string    `json:"id"`
		Subject          string    `json:"subject"`
		ReceivedDateTime time.Time `json:"receivedDateTime"`
		From             struct {
			EmailAddress struct {
				Name    string `json:"name"`
				Address string `json:"address"`
			} `json:"emailAddress"`
		} `json:"from"`
		Body struct {
			ContentType string `json:"contentType"`
			Content     string `json:"content"`
		} `json:"body"`
		InternetMessageHeaders []struct {
			Name  string `json:"name"`
			Value string `json:"value"`
		} `json:"internetMessageHeaders"`
	} `json:"value"`
	NextLink string `json:"@odata.nextLink"`
}

func New(tenantID, clientID, clientSecret string) *Client {
	return &Client{
		tenantID:     tenantID,
		clientID:     clientID,
		clientSecret: clientSecret,
		http:         &http.Client{Timeout: 60 * time.Second},
		tokenEndpoint: fmt.Sprintf(
			"https://login.microsoftonline.com/%s/oauth2/v2.0/token", tenantID),
		graphBase: "https://graph.microsoft.com/v1.0",
	}
}

// AccessToken returns a client-credentials token for Graph.
//
// Exported for `cti-mailer --check`, which decodes the token's claims to
// report which application roles the tenant actually consented to. That is the
// one question no amount of local configuration can answer, and the step
// people skip - a permission added in Entra without admin consent looks
// identical to one that was never added.
//
// Callers must not log the token. It is a bearer credential for the whole
// mailbox.
func (c *Client) AccessToken(ctx context.Context) (string, error) {
	return c.token(ctx)
}

func (c *Client) token(ctx context.Context) (string, error) {
	endpoint := c.tokenEndpoint
	form := url.Values{}
	form.Set("client_id", c.clientID)
	form.Set("client_secret", c.clientSecret)
	form.Set("scope", "https://graph.microsoft.com/.default")
	form.Set("grant_type", "client_credentials")

	req, err := http.NewRequestWithContext(ctx, http.MethodPost, endpoint, strings.NewReader(form.Encode()))
	if err != nil {
		return "", err
	}
	req.Header.Set("Content-Type", "application/x-www-form-urlencoded")

	resp, err := c.http.Do(req)
	if err != nil {
		return "", err
	}
	defer func() {
		_ = resp.Body.Close()
	}()
	body, err := io.ReadAll(resp.Body)
	if err != nil {
		return "", fmt.Errorf("failed to read graph token response: %w", err)
	}
	if resp.StatusCode < 200 || resp.StatusCode > 299 {
		return "", fmt.Errorf("graph token request failed: HTTP %d: %s", resp.StatusCode, string(body))
	}

	var tr tokenResponse
	if err := json.Unmarshal(body, &tr); err != nil {
		return "", err
	}
	if tr.AccessToken == "" {
		return "", fmt.Errorf("graph token response did not include access_token")
	}
	return tr.AccessToken, nil
}

// messagesURL builds the first-page request URL for a mailbox folder.
//
// Extracted so it can be tested without a network call. It exists because an
// unescaped space in $orderby shipped once: every OData *value* must be
// escaped, or the space lands in the HTTP request line and the edge rejects
// the request with an HTML "Bad Request" page before Graph's API layer sees
// it. That failure does not look like a Graph error, so it costs real time.
//
// The "$" prefixes stay literal rather than going through
// url.Values.Encode(), which would percent-encode them to %24. Graph accepts
// %24, but literal "$" matches its documentation and error messages, which
// keeps these URLs greppable against the docs.
func messagesURL(mailbox, folder string, since time.Time) string {
	return messagesURLBase("https://graph.microsoft.com/v1.0", mailbox, folder, since)
}

func messagesURLBase(base, mailbox, folder string, since time.Time) string {
	filter := fmt.Sprintf("receivedDateTime ge %s", since.UTC().Format(time.RFC3339))
	// internetMessageHeaders is requested so the mailbox cleanup lane can tell
	// an out-of-office auto-reply from a real advisory by what the sending
	// system declared, rather than by guessing from the subject. Graph returns
	// the full header set for a $select that names it.
	selectFields := "id,subject,receivedDateTime,from,body,internetMessageHeaders"

	params := []string{
		"$top=50",
		"$select=" + url.QueryEscape(selectFields),
		"$orderby=" + url.QueryEscape("receivedDateTime desc"),
		"$filter=" + url.QueryEscape(filter),
	}
	return fmt.Sprintf("%s/users/%s/mailFolders/%s/messages?%s",
		base,
		url.PathEscape(mailbox),
		url.PathEscape(folder),
		strings.Join(params, "&"),
	)
}

// graphError turns a failed response into something actionable.
//
// Graph reports its own errors as JSON. An HTML body means the request never
// reached Graph - it was rejected by the edge for being malformed - so saying
// so directly saves a long detour through permissions and mailbox settings
// that are not the problem.
func graphError(status int, body []byte, endpoint string) error {
	trimmed := strings.TrimSpace(string(body))

	if strings.HasPrefix(trimmed, "<") {
		return fmt.Errorf("graph request was rejected before reaching the API "+
			"(HTTP %d, HTML response). This means a malformed URL, almost always "+
			"an unescaped character in an OData query parameter such as a space "+
			"in $orderby or $filter.\nrequest: %s",
			status, endpoint)
	}

	var ge struct {
		Error struct {
			Code    string `json:"code"`
			Message string `json:"message"`
		} `json:"error"`
	}
	if err := json.Unmarshal(body, &ge); err == nil && ge.Error.Code != "" {
		hint := ""
		switch ge.Error.Code {
		case "ErrorAccessDenied", "Authorization_RequestDenied", "ErrorItemNotFound":
			hint = "\nhint: check that Mail.Read is granted as an APPLICATION " +
				"permission with admin consent, and that any Application Access " +
				"Policy includes this mailbox."
		case "ResourceNotFound", "ErrorInvalidUser", "MailboxNotEnabledForRESTAPI":
			hint = "\nhint: check GRAPH_MAILBOX is a real, licensed mailbox, and " +
				"that GRAPH_FOLDER names an existing folder."
		case "ErrorInvalidProperty", "BadRequest":
			hint = "\nhint: the OData query was understood but rejected - check " +
				"$select field names and the $filter datetime format."
		}
		return fmt.Errorf("graph messages request failed: HTTP %d %s: %s%s",
			status, ge.Error.Code, ge.Error.Message, hint)
	}

	if len(trimmed) > 800 {
		trimmed = trimmed[:800] + "..."
	}
	return fmt.Errorf("graph messages request failed: HTTP %d: %s", status, trimmed)
}

func (c *Client) RecentMessages(ctx context.Context, mailbox, folder string, since time.Time) ([]Message, error) {
	tok, err := c.token(ctx)
	if err != nil {
		return nil, err
	}

	endpoint := messagesURLBase(c.graphBase, mailbox, folder, since)

	var all []Message
	for endpoint != "" {
		req, err := http.NewRequestWithContext(ctx, http.MethodGet, endpoint, nil)
		if err != nil {
			return nil, err
		}
		req.Header.Set("Authorization", "Bearer "+tok)
		req.Header.Set("Prefer", `outlook.body-content-type="text"`)

		resp, err := c.http.Do(req)
		if err != nil {
			return nil, err
		}
		body, readErr := io.ReadAll(resp.Body)
		closeErr := resp.Body.Close()
		if readErr != nil {
			return nil, fmt.Errorf("failed to read graph messages response: %w", readErr)
		}
		if closeErr != nil {
			return nil, fmt.Errorf("failed to close graph messages response body: %w", closeErr)
		}
		if resp.StatusCode < 200 || resp.StatusCode > 299 {
			return nil, graphError(resp.StatusCode, body, endpoint)
		}

		var mr messagesResponse
		if err := json.Unmarshal(body, &mr); err != nil {
			return nil, err
		}
		for _, m := range mr.Value {
			from := strings.TrimSpace(m.From.EmailAddress.Address)
			if m.From.EmailAddress.Name != "" {
				from = fmt.Sprintf("%s <%s>", m.From.EmailAddress.Name, m.From.EmailAddress.Address)
			}
			msg := Message{
				ID:               m.ID,
				Subject:          m.Subject,
				ReceivedDateTime: m.ReceivedDateTime,
				From:             from,
				BodyText:         m.Body.Content,
			}
			for _, h := range m.InternetMessageHeaders {
				switch strings.ToLower(strings.TrimSpace(h.Name)) {
				case "auto-submitted":
					msg.AutoSubmitted = h.Value
				case "x-auto-response-suppress":
					msg.AutoResponseSuppress = h.Value
				case selfHeaderLower:
					msg.SelfSent = true
				}
			}
			// Mail we sent before SelfHeader existed carries no header, so the
			// sender is the backstop. The fleet sends AS this mailbox, so mail
			// from it to itself is our own report coming back round.
			if !msg.SelfSent && sameAddress(m.From.EmailAddress.Address, mailbox) {
				msg.SelfSent = true
			}
			all = append(all, msg)
		}
		endpoint = mr.NextLink
	}
	return all, nil
}

