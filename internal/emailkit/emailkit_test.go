func TestThePageIsTheFleetsShell(t *testing.T) {
	var b strings.Builder
	Open(&b, "Subject <x>", "CR", "Weekly", "Week of Monday")
	Lead(&b, Red, "Something <b>is</b> wrong")
	Tiles(&b, []Tile{{"high", 2, Red}, {"live", 5, Green}}, "caption")
	BodyOpen(&b)
	Section(&b, "needs action", Red.Fg)
	Item(&b, "a <plain> paragraph")
	Card(&b, Amber, "example.com <x>", "<div>line</div>")
	BodyClose(&b)
	Callout(&b, Yellow, "careful")
	Note(&b, "notice")
	Foot(&b, "one", "two")
	h := b.String()

	for _, want := range []string{
		"background:#12203a", "max-width:640px", "background:#eef1f5", // the shell
		"CR</div>", "Weekly", "Week of Monday",
		"border-left:4px solid #b3001b", // lead
		"HIGH", "LIVE", `width="50%"`,   // tiles: upper-cased, equal width
		"caption", "NEEDS ACTION", "text-transform:uppercase", // heading capitals are written, not left to CSS
		"border-left:4px solid #b25000", // card
		"one<br>", "two",
		"</body></html>",
	} {
		if !strings.Contains(h, want) {
			t.Errorf("page lacks %q", want)
		}
	}
	// Plain arguments are escaped; HTML arguments are not.
	for _, bad := range []string{"Subject <x>", "a <plain>", "example.com <x>"} {
		if strings.Contains(h, bad) {
			t.Errorf("%q reached the page unescaped", bad)
		}
	}
	if !strings.Contains(h, "Something <b>is</b> wrong") || !strings.Contains(h, "<div>line</div>") {
		t.Error("HTML arguments must be passed through")
	}
}

func TestCreditUsesTheFleetAttributionOrTheFallback(t *testing.T) {
	t.Setenv("FLEET_ATTRIBUTION", "")
	t.Setenv("FLEET_REPO_URL", "")
	if got := Credit("CR", "t", "Generated by <CR>"); got != "Generated by &lt;CR&gt;" {
		t.Errorf("fallback = %q (plain, so escaped)", got)
	}
	if got := CreditText("CR", "t", "Generated by CR"); got != "Generated by CR" {
		t.Errorf("text fallback = %q", got)
	}
	t.Setenv("FLEET_ATTRIBUTION", "Sent by the CR agent fleet")
	if got := Credit("CR", "t", "fallback"); got != "Sent by the CR agent fleet" {
		t.Errorf("credit = %q", got)
	}
	t.Setenv("FLEET_REPO_URL", "https://example.test/f")
	if got := Credit("CR", "t", "fallback"); !strings.Contains(got, `href="https://example.test/f"`) {
		t.Errorf("credit not linked: %q", got)
	}
}

// A Go lane must not write its own header band or page background: those are
// what make an email recognisably the fleet's, and a copy is how the owner
// emails came to be unstyled. (brief.py, which cannot import this package,
// reads the same tokens: TestBriefReadsTheSameTokens.)
func TestNoLaneDrawsItsOwnPageShell(t *testing.T) {
	root := filepath.Join("..", "..")
	var found = map[string]bool{}
	for _, dir := range []string{"internal", "cmd"} {
		err := filepath.WalkDir(filepath.Join(root, dir), func(p string, d fs.DirEntry, err error) error {
			if err != nil || d.IsDir() || !strings.HasSuffix(p, ".go") || strings.HasSuffix(p, "_test.go") {
				return err
			}
			rel, _ := filepath.Rel(root, p)
			rel = filepath.ToSlash(rel)
			if strings.HasPrefix(rel, "internal/emailkit/") {
				return nil
			}
			b, err := os.ReadFile(p) // #nosec G304 G122 -- a source file in this repository
			if err != nil {
				return err
			}
			if s := string(b); strings.Contains(s, Navy) || strings.Contains(s, PageBG) {
				found[rel] = true
			}
			return nil
		})
		if err != nil {
			t.Fatal(err)
		}
	}
	for rel := range found {
		t.Errorf("%s draws its own page shell (%s or %s). Build the email with "+
			"internal/emailkit instead, so it looks like the fleet's others.", rel, Navy, PageBG)
	}
}

