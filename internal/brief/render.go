package brief

import (
	"fmt"
	"strings"
	"time"

	"github.com/zany2dmax/cti-agent/internal/emailkit"
)

// Render is the HTML digest. now is the wall-clock time printed in the
// header and used for the subject's date.
func Render(data obj, kind string, now time.Time, env Env) string {
	c, meta := asObj(data["counts"]), asObj(getOr(data, "source_meta", obj{}))
	findings := asList(data["findings"])
	limits := RowLimits[kind]
	stamp := strings.TrimSpace(now.Format("Monday 02 January 2006, 15:04"))
	org := env.Org

	attrText, attrURL := env.attribution()
	var credit string
	switch {
	case attrText != "" && attrURL != "":
		credit = `<a href="` + htmlEscape(attrURL) + `" style="color:` + emailkit.Blue.Fg + `">` + htmlEscape(attrText) + `</a>`
	case attrText != "":
		credit = htmlEscape(attrText)
	default:
		credit = "Generated by the " + htmlEscape(org)
	}

	// The lead counts what the scanner confirmed, not the size of a band.
	nPresent, nUnverified := counts(asList(or(data["findings"], []any{})))
	unverifiedClause := ""
	if nUnverified > 0 {
		unverifiedClause = fmt.Sprintf(" A further %d exploited CVE%s could not be checked against "+
			"the scanner at all &mdash; unverified coverage, not a clean result.", nUnverified, pluralN(nUnverified))
	}
	var lead string
	var leadTone emailkit.Tone
	switch {
	case truthy(c["Sev5"]):
		y := "ies"
		if isOne(c["Sev5"]) {
			y = "y"
		}
		lead = "<b>" + htmlEscape(str(c["Sev5"])) + " vulnerabilit" + y + " " +
			"confirmed present in our environment and known to be exploited.</b> " +
			"These need attention today." + unverifiedClause
		leadTone = emailkit.Red
	case nPresent > 0:
		lead = fmt.Sprintf("No actively-exploited vulnerabilities are confirmed present. "+
			"%d confirmed present in the environment for this "+
			"week's patch cycle.%s", nPresent, unverifiedClause)
		leadTone = emailkit.Amber
	case nUnverified > 0:
		them := "it"
		if nUnverified != 1 {
			them = "them"
		}
		lead = fmt.Sprintf("<b>Nothing confirmed present in the environment.</b> But "+
			"%d actively-exploited CVE%s could not be checked "+
			"against the scanner &mdash; there is no QID mapping for "+
			"%s. That means we did "+
			"not look, not that we are clean. Resolving the coverage gap "+
			"is the action here.", nUnverified, pluralN(nUnverified), them)
		leadTone = emailkit.Amber
	case isZero(data["total"]):
		lead = "No CVEs appeared in the threat-intel mailbox in this window. " +
			"Nothing to action."
		leadTone = emailkit.Green
	default:
		lead = str(data["total"]) + " CVEs reviewed. None confirmed present in the " +
			"environment and none on the CISA KEV list. Nothing to action."
		leadTone = emailkit.Green
	}

	degraded := ""
	if truthy(data["degraded"]) {
		degraded = `
      <tr><td style="padding:0 0 14px 0">
        <div style="background:#fffbe6;border:1px solid #d69e2e;border-radius:4px;
                    padding:10px 12px;font:700 13px -apple-system,Segoe UI,Arial,sans-serif;
                    color:#744210">
          DEGRADED &mdash; these enrichment sources were unavailable this run:
          ` + htmlEscape(join(asList(data["degraded"]), ", ")) + `. Priorities below may understate risk.
        </div></td></tr>`
	}

	// KEV deadlines: one band, only when there is something to act on.
	kevd := asObj(or(data["kev_deadlines"], obj{}))
	switch {
	case truthy(kevd["overdue"]):
		cves := asList(getOr(kevd, "overdue_cves", []any{}))
		more := len(cves) - 6
		moreS := ""
		if more > 0 {
			moreS = fmt.Sprintf(" +%d more", more)
		}
		degraded += `
      <tr><td style="padding:0 0 14px 0">
        <div style="background:#fff5f5;border:1px solid #c53030;border-radius:4px;
                    padding:10px 12px;font:400 13px/1.5 -apple-system,Segoe UI,Arial,sans-serif;
                    color:#742a2a">
          <b>` + htmlEscape(str(kevd["overdue"])) + ` CISA KEV remediation deadline` + plural(kevd["overdue"]) + ` passed</b>
          &mdash; worst by ` + htmlEscape(str(getOr(kevd, "worst_overdue_days", json0))) + ` days.
          These are present in the environment and past a published federal
          due date: ` + htmlEscape(join(firstN(cves, 6), ", ")) + moreS + `.
        </div></td></tr>`
	case truthy(kevd["due_within_14d"]):
		degraded += `
      <tr><td style="padding:0 0 14px 0">
        <div style="background:#fffaf0;border:1px solid #dd6b20;border-radius:4px;
                    padding:10px 12px;font:400 13px/1.5 -apple-system,Segoe UI,Arial,sans-serif;
                    color:#7b341e">
          ` + htmlEscape(str(kevd["due_within_14d"])) + ` CISA KEV deadline` + plural(kevd["due_within_14d"]) + ` fall due within 14 days
          on vulnerabilities present here.
        </div></td></tr>`
	}

	var tiles strings.Builder
	for _, p := range SevOrder {
		b := pri[p]
		tiles.WriteString(`<td width="20%" align="center" style="background:` + b.bg + `;
              border-top:3px solid ` + b.fg + `;padding:10px 4px">
              <div style="font:700 24px -apple-system,Segoe UI,Arial,sans-serif;
                          color:` + b.fg + `">` + htmlEscape(str(getOr(c, p, json0))) + `</div>
              <div style="font:700 11px -apple-system,Segoe UI,Arial,sans-serif;
                          color:` + b.fg + `;letter-spacing:.5px">` + p + `</div></td>`)
	}

	tickets := asObj(data["_tickets"])
	var sections strings.Builder
	askedRows := asked(findings)
	askedIDs := map[string]bool{}
	if len(askedRows) > 0 {
		shown := firstN(askedRows, askedLimit)
		aMore := ""
		if hidden := len(askedRows) - askedLimit; hidden > 0 {
			aMore = fmt.Sprintf("<tr><td style='font:400 12px -apple-system,Segoe UI,Arial,sans-serif;"+
				"color:#718096;padding:0 0 14px 2px'>+%d more asked about "+
				"in the full report.</td></tr>", hidden)
		}
		fg := emailkit.Blue.Fg
		var blocks strings.Builder
		for _, f := range shown {
			blocks.WriteString(findingBlock(f, tickets, true))
			askedIDs[str(get(f, "cve"))] = true
		}
		fmt.Fprintf(&sections, `
      <tr><td style="padding:6px 0 8px 0">
        <div style="font:700 13px -apple-system,Segoe UI,Arial,sans-serif;
                    color:%s;letter-spacing:.6px;text-transform:uppercase;
                    border-bottom:2px solid %s;padding-bottom:5px">
          %s (%d)
        </div></td></tr>
      <tr><td style="padding:0 0 6px 0">
        <div style="font:400 12px/1.5 -apple-system,Segoe UI,Arial,sans-serif;
                    color:#4a5568;background:#f7fafc;border-left:3px solid %s;
                    padding:7px 10px">%s</div></td></tr>%s%s`,
			fg, fg, htmlEscape(askedHeading), len(askedRows), fg, htmlEscape(askedNote), blocks.String(), aMore)
	}
	for _, p := range SevOrder {
		group := byBand(findings, p)
		if len(group) == 0 || limits[p] == 0 {
			continue
		}
		// Counted in the heading, shown once: a row already listed under
		// "Asked about" is not repeated, and the band says so.
		var rowsP []any
		for _, f := range group {
			if !askedIDs[str(get(f, "cve"))] {
				rowsP = append(rowsP, f)
			}
		}
		above := len(group) - len(rowsP)
		shown := firstN(rowsP, limits[p])
		more := ""
		if hidden := len(rowsP) - limits[p]; hidden > 0 {
			more = fmt.Sprintf("<tr><td style='font:400 12px -apple-system,Segoe UI,Arial,sans-serif;"+
				"color:#718096;padding:0 0 14px 2px'>+%d more %s "+
				"in the full report.</td></tr>", hidden, p)
		}
		if above > 0 {
			more += fmt.Sprintf("<tr><td style='font:400 12px -apple-system,Segoe UI,Arial,sans-serif;"+
				"color:#718096;padding:0 0 14px 2px'>%d more %s listed "+
				"under Asked about, above.</td></tr>", above, p)
		}
		note := ""
		if n, ok := mixedNote[p]; ok && bandNeedsCaveat(group) {
			note = `
      <tr><td style="padding:0 0 6px 0">
        <div style="font:400 12px/1.5 -apple-system,Segoe UI,Arial,sans-serif;
                    color:#4a5568;background:#f7fafc;border-left:3px solid ` + pri[p].fg + `;
                    padding:7px 10px">` + n + `</div></td></tr>`
		}
		var blocks strings.Builder
		for _, f := range shown {
			blocks.WriteString(findingBlock(f, tickets, false))
		}
		fmt.Fprintf(&sections, `
      <tr><td style="padding:6px 0 8px 0">
        <div style="font:700 13px -apple-system,Segoe UI,Arial,sans-serif;
                    color:%s;letter-spacing:.6px;text-transform:uppercase;
                    border-bottom:2px solid %s;padding-bottom:5px">
          %s &mdash; %s (%d)
        </div></td></tr>%s%s%s`, pri[p].fg, pri[p].fg, p, pri[p].label, len(group), note, blocks.String(), more)
	}

	// Which number is which: the window count is not "new information", and
	// novelty is reported apart from volume.
	nv := asObj(or(data["novelty"], obj{}))
	novelty := ""
	switch {
	case truthy(nv["undetermined"]):
		novelty = "new vs previously reported: no history yet"
	case nv["new"] != nil:
		novelty = str(getOr(nv, "new", json0)) + " new, " + str(getOr(nv, "seen_before", json0)) + " previously reported"
	}
	var prov []string
	add := func(s string) {
		if s != "" {
			prov = append(prov, s)
		}
	}
	if truthy(meta["rollup"]) {
		add(esc(meta["rollup"]))
	}
	if truthy(meta["mailbox"]) {
		add("Mailbox " + esc(meta["mailbox"]))
	}
	if truthy(meta["emails"]) {
		add(esc(meta["emails"]) + " emails in the lookback window")
	}
	if truthy(meta["with_cves"]) {
		add(esc(meta["with_cves"]) + " mentioned a CVE")
	}
	add(novelty)
	if truthy(meta["provider"]) {
		add("Lookup: " + esc(getOr(meta, "provider", "qualys")))
	}
	if truthy(meta["since"]) {
		add("Since " + cut(esc(meta["since"]), 16))
	}
	heading := "Daily"
	if kind == "weekly" {
		heading = "Weekly"
	}

	return `<!DOCTYPE html>
<html><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>` + htmlEscape(Subject(data, kind, now)) + `</title></head>
<body style="margin:0;padding:0;background:` + emailkit.PageBG + `">
<table width="100%" cellpadding="0" cellspacing="0" role="presentation"
       style="background:` + emailkit.PageBG + `"><tr><td align="center" style="padding:16px 8px">
<table width="640" cellpadding="0" cellspacing="0" role="presentation"
       style="max-width:640px;background:#fff;border-radius:6px;overflow:hidden">

  <tr><td style="background:` + emailkit.Navy + `;padding:16px 20px">
    <div style="font:700 12px ` + emailkit.Font + `;
                color:` + emailkit.BandText + `;letter-spacing:1.2px;text-transform:uppercase">
      ` + htmlEscape(org) + `</div>
    <div style="font:700 17px ` + emailkit.Font + `;color:#fff">
      ` + heading + ` Brief</div>
    <div style="font:400 12px ` + emailkit.Font + `;
                color:` + emailkit.BandText + `;margin-top:3px">` + htmlEscape(stamp) + `</div></td></tr>

  <tr><td style="padding:16px 20px 0 20px">
    <table width="100%" cellpadding="0" cellspacing="0" role="presentation">
      <tr><td style="background:` + leadTone.Bg + `;border-left:4px solid ` + leadTone.Fg + `;
                     padding:12px 14px;font:400 14px/1.55 ` + emailkit.Font + `;
                     color:` + emailkit.Ink + `">` + lead + `</td></tr>
    </table></td></tr>

  <tr><td style="padding:14px 20px 0 20px">
    <table width="100%" cellpadding="0" cellspacing="0" role="presentation">
      <tr>` + tiles.String() + `</tr></table></td></tr>

  <tr><td style="padding:16px 20px 4px 20px">
    <table width="100%" cellpadding="0" cellspacing="0" role="presentation">
      ` + degraded + sections.String() + `
    </table></td></tr>

` + heldSection(data) + fleetTicketsSection(data) + advisoriesSection(data) + subjectsSection(data) + `
  <tr><td style="padding:8px 20px 18px 20px;border-top:1px solid ` + emailkit.Rule + `">
    <div style="font:400 11px/1.6 ` + emailkit.Font + `;
                color:` + emailkit.Muted + `">
      ` + strings.Join(prov, " &middot; ") + `<br>
      Presence is determined solely by the vulnerability lookup provider.
      Advisory text supplies urgency, never proof of exposure.
      <b>UNKNOWN</b> means no QID mapping existed &mdash; treat it as unverified
      coverage, not as clean.<br>
      ` + credit + ` &middot; ` + esc(data["generated"]) + `
    </div></td></tr>

</table></td></tr></table></body></html>`
}

func byBand(findings []any, p string) []any {
	var out []any
	for _, f := range findings {
		if s, ok := get(f, "priority").(string); ok && s == p {
			out = append(out, f)
		}
	}
	return out
}

// RenderText is the plain-text alternative: the same sections, the same
// caps, and truncation stated as it is in the HTML.
func RenderText(data obj, kind string, now time.Time, env Env) string {
	c := asObj(data["counts"])
	lines := []string{Subject(data, kind, now), strings.Repeat("=", 68), ""}
	tiles := make([]string, len(SevOrder))
	for i, p := range SevOrder {
		tiles[i] = p + " " + str(getOr(c, p, json0))
	}
	lines = append(lines, strings.Join(tiles, "   ")+"   (total "+str(data["total"])+")")
	if truthy(data["degraded"]) {
		lines = append(lines, "", "DEGRADED - unavailable this run: "+join(asList(data["degraded"]), ", "))
	}
	nov := asObj(or(data["novelty"], obj{}))
	switch {
	case truthy(nov["undetermined"]):
		lines = append(lines, "", "NEW vs SEEN: undetermined - no findings history yet")
	case nov["new"] != nil:
		lines = append(lines, "", "NEW since last run: "+str(getOr(nov, "new", json0))+
			"   previously reported: "+str(getOr(nov, "seen_before", json0)))
		if truthy(nov["new_cves"]) {
			lines = append(lines, "  new: "+join(firstN(asList(nov["new_cves"]), 10), ", "))
		}
	}
	kev := asObj(or(data["kev_deadlines"], obj{}))
	if truthy(kev["overdue"]) || truthy(kev["due_within_14d"]) {
		lines = append(lines, "", "CISA KEV: "+str(getOr(kev, "overdue", json0))+" OVERDUE"+
			" (worst by "+str(getOr(kev, "worst_overdue_days", json0))+"d),"+
			" "+str(getOr(kev, "due_within_14d", json0))+" due within 14d")
		if truthy(kev["overdue_cves"]) {
			lines = append(lines, "  overdue: "+join(firstN(asList(kev["overdue_cves"]), 8), ", "))
		}
	}
	lines = append(lines, "")
	limits := RowLimits[kind]
	tickets := asObj(or(data["_tickets"], obj{}))
	textRow := func(f any, withBand bool) []string {
		prod := ""
		if p, ok := productLabel(f); ok {
			if p == "" {
				p = "product not identified"
			}
			prod = "  [" + p + "]"
		}
		sev := ""
		if withBand {
			sev = "  " + str(get(f, "priority"))
		}
		out := []string{"  " + str(get(f, "cve")) + sev + prod + "  " + str(get(f, "status")) + "  " +
			str(or(get(f, "host_count"), json0)) + " host(s)",
			"    " + str(get(f, "rationale"))}
		if tl, ok := ticketCellText(f, tickets); ok && tl != "" {
			out = append(out, tl)
		}
		return out
	}
	findings := asList(data["findings"])
	askedRows := asked(findings)
	askedIDs := map[string]bool{}
	if len(askedRows) > 0 {
		lines = append(lines, fmt.Sprintf("%s (%d)", askedHeading, len(askedRows)), rule68, "  "+askedNote)
		for _, f := range firstN(askedRows, askedLimit) {
			lines = append(lines, textRow(f, true)...)
			askedIDs[str(get(f, "cve"))] = true
		}
		if len(askedRows) > askedLimit {
			lines = append(lines, fmt.Sprintf("  +%d more asked about in the full report.", len(askedRows)-askedLimit))
		}
		lines = append(lines, "")
	}
	for _, p := range SevOrder {
		group := byBand(findings, p)
		if len(group) == 0 || limits[p] == 0 {
			continue
		}
		var rowsP []any
		for _, f := range group {
			if !askedIDs[str(get(f, "cve"))] {
				rowsP = append(rowsP, f)
			}
		}
		lines = append(lines, fmt.Sprintf("%s - %s (%d)", p, pri[p].label, len(group)), rule68)
		if _, ok := mixedNote[p]; ok && bandNeedsCaveat(group) {
			lines = append(lines, "  NOTE: UNKNOWN rows below are unverified coverage, "+
				"not confirmed exposure.")
		}
		for _, f := range firstN(rowsP, limits[p]) {
			lines = append(lines, textRow(f, false)...)
		}
		if len(rowsP) > limits[p] {
			lines = append(lines, fmt.Sprintf("  +%d more %s in the full report.", len(rowsP)-limits[p], p))
		}
		if len(group) > len(rowsP) {
			lines = append(lines, fmt.Sprintf("  %d more %s listed under Asked about, above.", len(group)-len(rowsP), p))
		}
		lines = append(lines, "")
	}
	lines = append(lines, heldText(data)...)
	lines = append(lines, fleetTicketsText(data)...)
	lines = append(lines, advisoriesText(data)...)
	lines = append(lines, "Presence determined solely by the vulnerability lookup provider.",
		"UNKNOWN means the scanner had no mapping - not that we are clean.")
	attrText, attrURL := env.attribution()
	if attrText != "" {
		lines = append(lines, "", attrText)
		// The URL on its own line: a text-only reader cannot follow an anchor.
		if attrURL != "" {
			lines = append(lines, attrURL)
		}
	} else {
		lines = append(lines, "", "Generated by the "+env.Org)
	}
	return strings.Join(lines, "\n")
}
